/**
 * Generates the field descriptors that are too many to write by hand, from the
 * schema `generate-schema.ts` just wrote (`bun run schema` runs both):
 *
 *   src/fields/generated/themeTokens.ts   every theme token the curated THEME_SECTIONS do not already describe
 *   src/fields/generated/uiText.ts        every interface text key, with the English text as its default
 *
 * Labels are derived from the key path (sentence case, "colour"). Nothing here is
 * edited by hand: change the type, or the curated lists in `src/fields/`, and re-run.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { schemaPaths, type SchemaPath } from './schemaPaths.js';
import manifestSchema from '../src/schemas/manifest.schema.json' with { type: 'json' };
import { THEME_FIELDS } from '../src/fields/themeFields.js';
import { en } from '../../../src/translations/locales/en.js';

const root: any = manifestSchema;
const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../src/fields/generated');
mkdirSync(outDir, { recursive: true });

const WORDS: Record<string, string> = { url: 'URL', ui: 'UI', id: 'ID', css: 'CSS', geojson: 'GeoJSON', '3d': '3D', ios: 'iOS' };

/** `playButtonBackground` → `Play button background`; `colors.text.primary` → `Text primary`. */
function sentence(segments: string[]): string {
  const words = segments
    .flatMap((s) => s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[\s_-]+/))
    .map((w) => w.toLowerCase())
    .map((w) => (w === 'color' ? 'colour' : w === 'colors' ? 'colours' : w))
    .map((w) => WORDS[w] ?? w);
  const text = words.join(' ');
  return text.charAt(0).toUpperCase() + text.slice(1);
}

const q = (value: string) => JSON.stringify(value);
const header = (what: string) =>
  `// GENERATED by packages/schema/scripts/generate-fields.ts (\`bun run schema\`). Do not edit.\n// ${what}\n`;

// --- theme tokens -----------------------------------------------------------

type Kind = 'text' | 'color' | 'number' | 'boolean' | 'select' | 'fontstack';

function themeKind(p: SchemaPath): { kind: Kind; help?: string } {
  if (p.type === 'boolean') return { kind: 'boolean' };
  if (p.type === 'number') return { kind: 'number' };
  if (p.type === 'array') return { kind: 'fontstack', help: 'Comma-separated, most preferred first.' };
  if (p.enum) return { kind: 'select' };
  const last = p.path.split('.').pop()!;
  if (/^(colors|status)\./.test(p.path)) return { kind: 'color' };
  if (/shadow$/i.test(last)) return { kind: 'text', help: 'A CSS box-shadow, e.g. 0 2px 8px rgba(0, 0, 0, 0.1).' };
  if (/weight$/i.test(last)) return { kind: 'text', help: 'A CSS font weight, e.g. 400 or 600.' };
  if (/(fontsize|radius|size|height|blur)$/i.test(last)) return { kind: 'text', help: 'A CSS length, e.g. 14px or 0.875rem.' };
  if (/dasharray$/i.test(last)) return { kind: 'text', help: 'An SVG dash pattern, e.g. "8 6".' };
  if (/(color|background|fill|stroke|text|icon|gradienttop|gradientbottom)$/i.test(last)) return { kind: 'color' };
  return { kind: 'text' };
}

const curated = new Set(THEME_FIELDS.map((f) => f.key));
// id/name/description/extends are described by hand (THEME_IDENTITY_FIELDS).
const themeLeaves = schemaPaths(root, root.definitions.CustomTheme).filter(
  (p) => p.leaf && !['id', 'name', 'description', 'extends'].includes(p.path) && !curated.has(p.path),
);

const bySection = new Map<string, SchemaPath[]>();
for (const p of themeLeaves) {
  const section = p.path.split('.')[0];
  bySection.set(section, [...(bySection.get(section) ?? []), p]);
}

let theme = header(`${themeLeaves.length} theme tokens not covered by the curated sections of fields/themeFields.ts.`);
theme += `import type { ThemeSection } from '../themeFields.js';\n\n`;
theme += `/** Every remaining theme token, grouped by the part of the app it styles. */\nexport const THEME_TOKEN_SECTIONS: ThemeSection[] = [\n`;
for (const [section, paths] of bySection) {
  theme += `  {\n    title: ${q(sentence([section]))},\n    fields: [\n`;
  for (const p of paths) {
    const { kind, help } = themeKind(p);
    const rest = p.path.split('.').slice(1);
    const parts = [`key: ${q(p.path)}`, `label: ${q(sentence(rest.length ? rest : [section]))}`, `kind: ${q(kind)}`];
    if (kind === 'select') {
      parts.push(`options: [${(p.enum ?? []).map((v) => `{ value: ${q(String(v))}, label: ${q(sentence([String(v)]))} }`).join(', ')}]`);
    }
    if (help) parts.push(`help: ${q(help)}`);
    theme += `      { ${parts.join(', ')} },\n`;
  }
  theme += `    ],\n  },\n`;
}
theme += `];\n`;
writeFileSync(resolve(outDir, 'themeTokens.ts'), theme);

// --- interface text ---------------------------------------------------------

const englishAt = (path: string): string => path.split('.').reduce<any>((node, key) => node?.[key], en);
const uiLeaves = schemaPaths(root, root.definitions.UiText).filter((p) => p.leaf);

let ui = header(`${uiLeaves.length} interface text keys. \`default\` is the built-in English text.`);
ui += `import type { FieldSpec } from '../stopTypes.js';\n\n`;
ui += `/** One group of interface text, e.g. everything on the rating screen. */\nexport interface UiTextSection {\n  title: string;\n  fields: FieldSpec[];\n}\n\n`;
ui += `/** Every key of \`Translations\`, overridable per language through \`manifest.ui\`. */\nexport const UI_TEXT_SECTIONS: UiTextSection[] = [\n`;
const uiSections = new Map<string, SchemaPath[]>();
for (const p of uiLeaves) uiSections.set(p.path.split('.')[0], [...(uiSections.get(p.path.split('.')[0]) ?? []), p]);
for (const [section, paths] of uiSections) {
  ui += `  {\n    title: ${q(sentence([section]))},\n    fields: [\n`;
  for (const p of paths) {
    const text = englishAt(p.path);
    if (typeof text !== 'string') throw new Error(`${p.path}: no English text to use as the default`);
    const rest = p.path.split('.').slice(1);
    ui += `      { key: ${q(p.path)}, label: ${q(sentence(rest))}, kind: 'text', translatable: true, default: ${q(text)} },\n`;
  }
  ui += `    ],\n  },\n`;
}
ui += `];\n`;
writeFileSync(resolve(outDir, 'uiText.ts'), ui);

console.log(`✓ ${themeLeaves.length} theme tokens → src/fields/generated/themeTokens.ts`);
console.log(`✓ ${uiLeaves.length} interface text keys → src/fields/generated/uiText.ts`);
